-- ════════════════════════════════════════════════════════════════════
-- ترقية: تصحيح شرط التكرار في جدول تراخيص جمع المال (FundraisingLicenses)
-- ════════════════════════════════════════════════════════════════════
-- المشكلة: الشرط الحالي في القاعدة يمنع تكرار "نفس رقم الترخيص" لنفس
--   الجمعية إطلاقاً - حتى لو في سنوات مختلفة. وده غير صحيح لأن نفس
--   الجمعية ممكن ياخد نفس رقم الترخيص في سنة تانية فعلاً.
-- الحل: نخلي الشرط يمنع فقط تكرار (نفس الجمعية + نفس الرقم + نفس سنة
--   الإصدار) معاً - وهو الشيء الوحيد المستحيل حدوثه فعلياً.
--
-- طريقة التشغيل: افتحي SQL Server Management Studio (أو أي أداة تنفيذ SQL)
-- متصلة بقاعدة NGO_System، وشغّلي السكريبت ده مرة واحدة بس.
-- ════════════════════════════════════════════════════════════════════

USE NGO_System;
GO

-- 1) نتأكد الأول إن مفيش بيانات موجودة بالفعل هتتعارض مع الشرط الجديد
--    (نظرياً مستحيل يحصل لأن الشرط القديم كان أشد، بس بنتأكد للأمان)
IF EXISTS (
  SELECT OrgID, LicenseNumber, IssueYear
  FROM FundraisingLicenses
  GROUP BY OrgID, LicenseNumber, IssueYear
  HAVING COUNT(*) > 1
)
BEGIN
  PRINT '⚠️ تحذير: يوجد بالفعل صفوف مكررة بنفس (الجمعية + رقم الترخيص + سنة الإصدار). راجعيها يدوياً قبل المتابعة.';
END
ELSE
BEGIN
  -- 2) حذف الشرط القديم
  IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE name='UQ_License')
    ALTER TABLE FundraisingLicenses DROP CONSTRAINT UQ_License;

  -- 3) إضافة الشرط الجديد الصحيح (يشمل سنة الإصدار)
  --    ملحوظة: بما إن IssueYear ممكن يكون NULL أحياناً، وSQL Server مايعتبرش
  --    قيمتين NULL متساويتين في UNIQUE، فالحماية دي كافية عملياً. لو حبيتي
  --    حماية أقوى حتى مع NULL ممكن نستخدم Filtered Index بدل الشرط ده.
  ALTER TABLE FundraisingLicenses
    ADD CONSTRAINT UQ_License UNIQUE (OrgID, LicenseNumber, IssueYear);

  PRINT '✅ تم تحديث الشرط بنجاح: التكرار الممنوع دلوقتي هو (نفس الجمعية + نفس رقم الترخيص + نفس سنة الإصدار) بس.';
END
GO
