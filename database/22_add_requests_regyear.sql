-- ترقية 18: إصلاح مشكلة "سنة القيد" في طلبات إضافة الجمعيات
-- المشكلة: جدول AddRequests ما كانش فيه عمود RegYear من الأساس،
-- فسنة القيد اللي بيكتبها مقدّم الطلب كانت بتضيع تمامًا ولا تتحفظ
-- في أي مكان، وشاشة المراجعة/القبول كانت بالتالي مضطرة تفترض دايمًا
-- "السنة الحالية" بدل السنة الحقيقية اللي اتكتبت وقت التسجيل.
-- ══════════════════════════════════════════════════
USE NGO_System;
GO

IF COL_LENGTH('AddRequests','RegYear') IS NULL
    ALTER TABLE AddRequests ADD RegYear INT NULL;
GO

PRINT N'✅ تم تحديث جدول AddRequests ليدعم حفظ سنة القيد اللي كتبها مقدّم الطلب';
GO
