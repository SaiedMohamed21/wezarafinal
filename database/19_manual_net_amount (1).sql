-- ترقية 18: تحويل "صافي الحصيلة" من عمود محسوب تلقائيًا (الإيرادات - المصروفات)
-- إلى عمود عادي يُكتب فيه يدويًا - بناءً على طلب: الاستمارة متعرضش خانتي
-- الإيرادات/المصروفات بعد كده، وموظف جمع المال يكتب صافي الحصيلة مباشرة.
-- ملحوظة: القيم القديمة المحسوبة سلفًا (Revenue-Expenses) بتتحفظ زي ما هي
-- كنقطة بداية، وبعد كده تبقى قابلة للتعديل اليدوي الحر.
-- ══════════════════════════════════════════════════
USE NGO_System;
GO

-- 1) نحفظ القيم الحالية المحسوبة في عمود مؤقت
ALTER TABLE FundraisingLicenses ADD NetAmount_tmp DECIMAL(18,2) NULL;
GO
UPDATE FundraisingLicenses SET NetAmount_tmp = NetAmount;
GO

-- 2) نحذف العمود المحسوب القديم
ALTER TABLE FundraisingLicenses DROP COLUMN NetAmount;
GO

-- 3) نضيفه من جديد كعمود عادي قابل للكتابة اليدوية، ونرجّع فيه القيم المحفوظة
EXEC sp_rename 'FundraisingLicenses.NetAmount_tmp', 'NetAmount', 'COLUMN';
GO

PRINT N'✅ تم تحويل صافي الحصيلة (NetAmount) إلى عمود يُكتب يدويًا. القيم القديمة محفوظة كما كانت.';
GO
