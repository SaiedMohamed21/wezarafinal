INSERT INTO FundraisingLicenses
  (OrgID, LicenseNumber, LicenseStatus, IssueDate, IssueMonth, IssueYear,
   StartDate, EndDate, LiquidationDate, LiquidationMonth, LiquidationYear,
   Revenue, Expenses, LiquidationStatus, DataType, CollectionMethods, LicensePurpose, CreatedAt)
