       s.StartDate, s.EndDate, NULL, NULL, NULL,
       NULL, NULL, NULL, N'جديدة', s.CollectionMethods, s.LicensePurpose, GETDATE()
FROM #Stage202607 s
JOIN Organizations o
  ON (s.Level = N'مركزي' AND o.Level = N'مركزي' AND o.RegNum = s.RegNum)
  OR (s.Level = N'مديرية' AND o.Level = N'مديرية' AND o.RegNum = s.RegNum
      AND ISNULL(o.Governorate,N'') = ISNULL(s.Governorate,N''))
WHERE NOT EXISTS (
  SELECT 1 FROM FundraisingLicenses fl
  WHERE fl.OrgID = o.OrgID AND fl.LicenseNumber = s.LicenseNumber
    AND ISNULL(fl.IssueYear,-1) = ISNULL(s.IssueYear,-1)
    AND ISNULL(fl.IsDeleted,0) = 0
);
